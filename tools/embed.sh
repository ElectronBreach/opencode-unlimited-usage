#!/bin/bash
# rebuild the self-contained payload inside install.sh.
#
# the one-line install in the README pipes install.sh from github. this repo's
# macOS branch is not published (raw .../macos/install.sh is 404), and the
# upstream main branch is the linux build. so the installer carries its own
# scripts: a single file installs a working macOS build with no network.
#
# run me after changing any script: bash tools/embed.sh
# verify the payload is not stale:  bash tools/embed.sh --check
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)
MODE="${1:-embed}"

build_payload(){
  local tmp tgz b64 sha
  tmp=$(mktemp -d /tmp/ouc-embed.XXXXXX)
  mkdir -p "$tmp/payload/scripts"
  cp scripts/*.sh "$tmp/payload/scripts/"
  cp AGENTS.md "$tmp/payload/AGENTS.md"
  cp uninstall.sh "$tmp/payload/uninstall.sh"
  ( cd "$tmp/payload" && tar -czf "$tmp/payload.tgz" . )
  sha=$(shasum -a 256 "$tmp/payload.tgz" | awk '{print $1}')
  b64=$(base64 < "$tmp/payload.tgz" | tr -d '\n')
  rm -rf "$tmp"
  printf '%s\n%s\n' "$sha" "$b64"
}

OUT=$(build_payload)
WANT_SHA=$(printf '%s' "$OUT" | head -1)
B64=$(printf '%s' "$OUT" | tail -1)

if [ "$MODE" = "--check" ]; then
  GOT=$(grep -o '^# payload-sha: [a-f0-9]*' install.sh | awk '{print $3}')
  if [ "$GOT" = "$WANT_SHA" ]; then
    echo "payload is current ($WANT_SHA)"
    exit 0
  fi
  echo "STALE PAYLOAD: install.sh has ${GOT:-none}, scripts hash $WANT_SHA" >&2
  echo "run: bash tools/embed.sh" >&2
  exit 1
fi

python3 - "$ROOT/install.sh" "$B64" "$WANT_SHA" <<'PY'
import re, sys
path, b64, sha = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(path).read()
block = "# payload-sha: " + sha + "\n"
block += "# ---- embedded payload (generated by tools/embed.sh — do not edit) ----\n: <<'OUC_PAYLOAD'\n"
block += b64
block += "\nOUC_PAYLOAD\n"
pat = re.compile(r"(?:# payload-sha: [a-f0-9]*\n)?# ---- embedded payload \(generated by tools/embed\.sh.*?\n: <<'OUC_PAYLOAD'\n.*?\nOUC_PAYLOAD\n", re.S)
if pat.search(s):
    s = pat.sub(block, s, count=1)
else:
    s = s.rstrip("\n") + "\n\n" + block
open(path, "w").write(s)
print("payload embedded:", len(b64), "base64 chars, sha", sha[:12])
PY

chmod +x install.sh
bash -n install.sh
echo "install.sh is now standalone ($(wc -c < install.sh) bytes)"
